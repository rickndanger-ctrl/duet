// Turns Rick's Musa art (his own Muse character, a 1254x1254 master image) into what Hey Muse
// draws on the lens (app/src/musa-pixels.ts): the 47x48 grey head-and-shoulders bust at the top, and his 22x22 face for
// the mark beside Muse's words. Needs ffmpeg.
//   node scripts/musa-sprite.mjs path/to/master.png
// The crop is the bust of that master: beanie top to the upper chest, centred on the face.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
const src = process.argv[2]
if (!src) { console.error('usage: node scripts/musa-sprite.mjs master.png'); process.exit(1) }
const W = 47, H = 48
const raw = execFileSync('ffmpeg', ['-loglevel', 'error', '-i', src, '-vf', `crop=637:649:309:0,scale=${W}:${H}:flags=area,format=gray`, '-f', 'rawvideo', '-'])
if (raw.length !== W * H) throw new Error(`expected ${W * H} bytes, got ${raw.length}`)
const F = 22
const face = execFileSync('ffmpeg', ['-loglevel', 'error', '-i', src, '-vf', `crop=440:470:410:20,scale=${F}:${F}:flags=area,format=gray`, '-f', 'rawvideo', '-'])
if (face.length !== F * F) throw new Error(`expected ${F * F} face bytes, got ${face.length}`)
writeFileSync(new URL('../app/src/musa-pixels.ts', import.meta.url), `// Generated by scripts/musa-sprite.mjs from Rick's Musa art: grey, one byte per pixel (0 = black), base64.
/** The bust on the lens. */
export const MUSA_W = ${W}, MUSA_H = ${H};
export const MUSA_GREY = '${raw.toString('base64')}';
/** His face (beanie to smile), for the mark beside Muse's words. */
export const MUSA_FACE_SIZE = ${F};
export const MUSA_FACE = '${face.toString('base64')}';
`)
console.log(`wrote app/src/musa-pixels.ts (${W}x${H} bust, ${F}x${F} face)`)
